// Authentication controller: register, email verification, login, forgotten password, logout, current user
const bcrypt = require('bcryptjs'); // pure JavaScript bcrypt: same API, nothing to compile on install
const { randomInt } = require('node:crypto');
const { Op } = require('sequelize');
const { User } = require('../models');
const { validateRegister, validateLogin, validateEmail, validatePassword } = require('../validators');
const { sendMail, canDeliverCodes } = require('../services/mailer');

const SALT_ROUNDS = 12;
const CODE_TTL_MS = 10 * 60 * 1000; // a code is valid for 10 minutes
const MAX_ATTEMPTS = 5;

// Turns req.session.regenerate (callback-based) into a Promise so we can use await
const regenerateSession = (req) =>
  new Promise((resolve, reject) => req.session.regenerate((err) => (err ? reject(err) : resolve())));

// What we send to the front end: never the password hash
const publicUser = (u) => ({ id: u.id, email: u.email, username: u.username, role: u.role });

// Random 6-digit code; only its bcrypt hash is kept in the session
async function createCode() {
  const code = String(randomInt(0, 1_000_000)).padStart(6, '0');
  return { code, codeHash: await bcrypt.hash(code, SALT_ROUNDS) };
}

// Checks a code stored in the session (expiry, number of attempts, value)
async function checkCode(pending, code) {
  if (!pending || Date.now() >= pending.expiresAt || pending.attempts >= MAX_ATTEMPTS) {
    return 'This code has expired. Ask for a new one.';
  }
  if (typeof code !== 'string' || !/^\d{6}$/.test(code)) return 'Enter a six-digit code.';
  pending.attempts += 1;
  if (!(await bcrypt.compare(code, pending.codeHash))) return 'Incorrect code.';
  return null;
}

async function startEmailVerification(req, user) {
  const { code, codeHash } = await createCode();
  await sendMail({
    to: user.email,
    subject: "Mobil'Efrei – Confirm your email",
    text: `Your verification code is ${code}. It is valid for 10 minutes.`,
  });
  await regenerateSession(req);
  req.session.pendingVerification = { userId: user.id, codeHash, expiresAt: Date.now() + CODE_TTL_MS, attempts: 0 };
}

// POST /api/auth/register
exports.register = async (req, res) => {
  const errors = validateRegister(req.body);
  if (errors.length) return res.status(400).json({ error: errors.join(' ') });

  const email = req.body.email.trim().toLowerCase();
  const username = req.body.username.trim();

  // Parameterised query generated by Sequelize: no SQL injection possible
  const existing = await User.findOne({ where: { [Op.or]: [{ email }, { username }] } });
  if (existing) return res.status(409).json({ error: 'This email or username is already taken.' });
  if (!canDeliverCodes()) return res.status(503).json({ error: 'Email verification is unavailable.' });

  // Asynchronous password hashing with bcrypt (the salt is included automatically)
  const passwordHash = await bcrypt.hash(req.body.password, SALT_ROUNDS);
  const user = await User.create({ email, username, passwordHash });

  await startEmailVerification(req, user);
  res.status(201).json({ requiresVerification: true });
};

// POST /api/auth/login  (login = email OR username)
exports.login = async (req, res) => {
  const errors = validateLogin(req.body);
  if (errors.length) return res.status(400).json({ error: errors.join(' ') });

  const login = req.body.login.trim();
  const user = await User.scope('withPassword').findOne({
    where: { [Op.or]: [{ email: login.toLowerCase() }, { username: login }] },
  });

  // Same message in both cases so we don't reveal whether the account exists
  const ok = user && (await bcrypt.compare(req.body.password, user.passwordHash));
  if (!ok) return res.status(401).json({ error: 'Incorrect email/username or password.' });

  // Account not verified yet: a new code is sent
  if (!user.emailVerifiedAt) {
    if (!canDeliverCodes()) return res.status(503).json({ error: 'Email verification is unavailable.' });
    await startEmailVerification(req, user);
    return res.json({ requiresVerification: true });
  }

  await regenerateSession(req); // new session id (protection against session fixation)
  req.session.userId = user.id;
  req.session.role = user.role;
  res.json({ user: publicUser(user) });
};

// POST /api/auth/verify-email
exports.verifyEmail = async (req, res) => {
  const pending = req.session.pendingVerification;
  const error = await checkCode(pending, req.body?.code);
  if (error) return res.status(400).json({ error });

  const user = await User.findByPk(pending.userId);
  if (!user) return res.status(400).json({ error: 'Account not found.' });
  if (!user.emailVerifiedAt) await user.update({ emailVerifiedAt: new Date() });

  await regenerateSession(req);
  req.session.userId = user.id;
  req.session.role = user.role;
  res.json({ user: publicUser(user) });
};

// POST /api/auth/forgot-password  { email }
// Always the same answer, so nobody can find out which emails have an account
exports.forgotPassword = async (req, res) => {
  const errors = validateEmail(req.body?.email);
  if (errors.length) return res.status(400).json({ error: errors.join(' ') });
  if (!canDeliverCodes()) return res.status(503).json({ error: 'Password reset is unavailable.' });

  const email = req.body.email.trim().toLowerCase();
  const user = await User.findOne({ where: { email } });

  if (user) {
    const { code, codeHash } = await createCode();
    await sendMail({
      to: user.email,
      subject: "Mobil'Efrei – Reset your password",
      text: `Your password reset code is ${code}. It is valid for 10 minutes. If you did not ask for it, ignore this email.`,
    });
    req.session.pendingReset = { userId: user.id, codeHash, expiresAt: Date.now() + CODE_TTL_MS, attempts: 0 };
  } else {
    delete req.session.pendingReset;
  }
  res.json({ message: 'If an account exists for this email, a 6-digit code has been sent.' });
};

// POST /api/auth/reset-password  { code, password }
exports.resetPassword = async (req, res) => {
  const pending = req.session.pendingReset;
  const error = await checkCode(pending, req.body?.code);
  if (error) return res.status(400).json({ error });

  const errors = validatePassword(req.body?.password);
  if (errors.length) return res.status(400).json({ error: errors.join(' ') });

  const user = await User.findByPk(pending.userId);
  if (!user) return res.status(400).json({ error: 'Account not found.' });

  await user.update({
    passwordHash: await bcrypt.hash(req.body.password, SALT_ROUNDS),
    emailVerifiedAt: user.emailVerifiedAt || new Date(), // the code proves the user owns this email
  });
  delete req.session.pendingReset;
  res.json({ message: 'Password updated. You can now sign in.' });
};

// POST /api/auth/logout
exports.logout = (req, res, next) => {
  req.session.destroy((err) => {
    if (err) return next(err);
    res.clearCookie('mobilefrei.sid');
    res.json({ message: 'Signed out.' });
  });
};

// GET /api/auth/me: lets the front end know whether the user is signed in
exports.me = async (req, res) => {
  if (!req.session.userId) return res.json({ user: null });
  const user = await User.findByPk(req.session.userId);
  res.json({ user: user ? publicUser(user) : null });
};
